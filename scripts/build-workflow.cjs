const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const root = resolve(__dirname, '..');
const source = readFileSync(resolve(root, 'src/auto-merge.cjs'), 'utf8').replace(/module\.exports = \{ autoMerge \};\s*$/, '');
const script = source + `
const result = await autoMerge({ github, context, core, config: {
  pullNumber: process.env.PULL_NUMBER,
  expectedHead: process.env.EXPECTED_HEAD,
  headBranch: process.env.HEAD_BRANCH,
  requiredChecks: process.env.REQUIRED_CHECKS,
  expectedTokenActor: process.env.EXPECTED_TOKEN_ACTOR,
  hasExplicitToken: process.env.HAS_EXPLICIT_TOKEN === 'true',
  requiredLabel: process.env.REQUIRED_LABEL,
  excludeDependabot: process.env.EXCLUDE_DEPENDABOT === 'true',
  requireDependabot: process.env.REQUIRE_DEPENDABOT === 'true',
  dryRun: process.env.DRY_RUN === 'true',
} });
core.setOutput('outcome', result.outcome);
core.setOutput('number', result.number || '');
core.setOutput('merge-sha', result.sha || '');
core.info(JSON.stringify(result));
await core.summary.addHeading('Shared merge result').addRaw(JSON.stringify(result)).write();
`;
const workflow = `# Generated by scripts/build-workflow.cjs. Edit src/auto-merge.cjs and regenerate.
name: Shared merge helper
on:
  workflow_call:
    inputs:
      pull-number:
        type: string
        default: ''
      expected-head:
        type: string
        default: ''
      head-branch:
        type: string
        default: ''
      required-checks:
        type: string
        required: true
      expected-token-actor:
        type: string
        default: ''
      required-label:
        type: string
        default: ''
      exclude-dependabot:
        type: boolean
        default: false
      require-dependabot:
        type: boolean
        default: false
      dry-run:
        type: boolean
        default: false
    secrets:
      token:
        required: false
    outputs:
      outcome:
        value: \${{ jobs.merge.outputs.outcome }}
      number:
        value: \${{ jobs.merge.outputs.number }}
      merge-sha:
        value: \${{ jobs.merge.outputs.merge-sha }}

# Permission levels come from the caller. A named existing token may be passed;
# no secrets inheritance, credentials persisted, checkout, or PR execution.
jobs:
  merge:
    name: Shared auto-merge
    runs-on: ubuntu-latest
    timeout-minutes: 5
    outputs:
      outcome: \${{ steps.merge.outputs.outcome }}
      number: \${{ steps.merge.outputs.number }}
      merge-sha: \${{ steps.merge.outputs.merge-sha }}
    steps:
      - name: Recheck policy and merge the verified head
        id: merge
        uses: actions/github-script@3a2844b7e9c422d3c10d287c895573f7108da1b3 # v9.0.0; MIT
        env:
          PULL_NUMBER: \${{ inputs.pull-number }}
          EXPECTED_HEAD: \${{ inputs.expected-head }}
          HEAD_BRANCH: \${{ inputs.head-branch }}
          REQUIRED_CHECKS: \${{ inputs.required-checks }}
          HAS_EXPLICIT_TOKEN: \${{ secrets.token != '' }}
          EXPECTED_TOKEN_ACTOR: \${{ inputs.expected-token-actor }}
          REQUIRED_LABEL: \${{ inputs.required-label }}
          EXCLUDE_DEPENDABOT: \${{ inputs.exclude-dependabot }}
          REQUIRE_DEPENDABOT: \${{ inputs.require-dependabot }}
          DRY_RUN: \${{ inputs.dry-run }}
        with:
          github-token: \${{ secrets.token || github.token }}
          script: |
${script.trimEnd().split('\n').map(line => '            ' + line).join('\n')}
`;
const path = resolve(root, '.github/workflows/merge.yml');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== workflow) throw new Error('Generated workflow differs from tested source. Run node scripts/build-workflow.cjs.');
} else writeFileSync(path, workflow);
